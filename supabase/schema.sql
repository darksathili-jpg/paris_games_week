alter table public.visit_sessions enable row level security;
alter table public.profiles enable row level security;
alter table public.responses enable row level security;
alter table public.progress enable row level security;

-- Nettoyage idempotent des policies
drop policy if exists visit_sessions_teacher_select on public.visit_sessions;
drop policy if exists visit_sessions_teacher_insert on public.visit_sessions;
drop policy if exists visit_sessions_teacher_update on public.visit_sessions;
drop policy if exists visit_sessions_teacher_delete on public.visit_sessions;
drop policy if exists profiles_self_teacher_select on public.profiles;
drop policy if exists profiles_teacher_update on public.profiles;
drop policy if exists responses_self_teacher_select on public.responses;
drop policy if exists responses_self_insert on public.responses;
drop policy if exists responses_self_update on public.responses;
drop policy if exists responses_self_teacher_delete on public.responses;
drop policy if exists progress_self_teacher_select on public.progress;
drop policy if exists progress_self_insert on public.progress;
drop policy if exists progress_self_update on public.progress;
drop policy if exists progress_self_teacher_delete on public.progress;

create policy visit_sessions_teacher_select
on public.visit_sessions for select to authenticated
using (public.is_teacher());

create policy visit_sessions_teacher_insert
on public.visit_sessions for insert to authenticated
with check (public.is_teacher());

create policy visit_sessions_teacher_update
on public.visit_sessions for update to authenticated
using (public.is_teacher()) with check (public.is_teacher());

create policy visit_sessions_teacher_delete
on public.visit_sessions for delete to authenticated
using (public.is_teacher());

create policy profiles_self_teacher_select
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_teacher());

create policy profiles_teacher_update
on public.profiles for update to authenticated
using (public.is_teacher()) with check (public.is_teacher());

create policy responses_self_teacher_select
on public.responses for select to authenticated
using (user_id = auth.uid() or public.is_teacher());

create policy responses_self_insert
on public.responses for insert to authenticated
with check (
  user_id = auth.uid()
  and visit_session_id = (select p.visit_session_id from public.profiles p where p.id = auth.uid())
);

create policy responses_self_update
on public.responses for update to authenticated
using (
  user_id = auth.uid()
  or public.is_teacher()
)
with check (
  (user_id = auth.uid() and visit_session_id = (select p.visit_session_id from public.profiles p where p.id = auth.uid()))
  or public.is_teacher()
);

create policy responses_self_teacher_delete
on public.responses for delete to authenticated
using (user_id = auth.uid() or public.is_teacher());

create policy progress_self_teacher_select
on public.progress for select to authenticated
using (user_id = auth.uid() or public.is_teacher());

create policy progress_self_insert
on public.progress for insert to authenticated
with check (
  user_id = auth.uid()
  and visit_session_id = (select p.visit_session_id from public.profiles p where p.id = auth.uid())
);

create policy progress_self_update
on public.progress for update to authenticated
using (user_id = auth.uid() or public.is_teacher())
with check (
  (user_id = auth.uid() and visit_session_id = (select p.visit_session_id from public.profiles p where p.id = auth.uid()))
  or public.is_teacher()
);

create policy progress_self_teacher_delete
on public.progress for delete to authenticated
using (user_id = auth.uid() or public.is_teacher());

-- Permissions API. Le RLS reste l'autorité finale.
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.visit_sessions to authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.responses to authenticated;
grant select, insert, update, delete on public.progress to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.join_visit_session(text,text,text) to authenticated;
grant execute on function public.is_teacher() to authenticated;

